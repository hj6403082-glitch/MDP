"""
Phase A - reproducible data audit for the MDP air-quality dataset.

Runs on data/raw/telemetry/*.parquet and writes a data-quality report, a data
dictionary, and per-station / per-pollutant coverage tables to audit/reports/.

It does NOT modify the raw data. Every number it prints is derived from the
committed Parquet files, so the report is fully reproducible:

    python audit/data_audit.py

Scope (see the paper's Phase A requirements): coverage, duplicates, operating
periods, pollutant availability by station and season, missing timestamps vs
missing values, unit/provenance metadata (presence/absence), suspicious values,
timestamp semantics, weather provenance, and geographic coverage.
"""

from __future__ import annotations

import glob
import json
import os
from datetime import timezone

import numpy as np
import pandas as pd

RAW_GLOB = "data/raw/telemetry/*.parquet"
OUT_DIR = "audit/reports"

ID_COLS = ["timestamp", "station_id", "city", "country"]
POLLUTANTS = ["co", "no", "no2", "ozone", "pm10", "pm25", "so2"]
WEATHER = ["temperature", "relative_humidity", "wind_speed", "pressure"]

# Plausibility ranges for gross-error screening (ambient, hourly).
# These are screening bounds, not calibration; values outside are flagged, not
# removed. Pollutant units are UNKNOWN in the data (see unit audit) so these
# assume the common OpenAQ reporting unit for each parameter.
PLAUSIBLE = {
    "co": (0, 50_000),       # if ug/m3 this is generous; if mg/m3, see unit flag
    "no": (0, 2_000),
    "no2": (0, 1_000),
    "ozone": (0, 1_000),
    "pm10": (0, 3_000),
    "pm25": (0, 2_000),
    "so2": (0, 2_000),
    "temperature": (-20, 60),
    "relative_humidity": (0, 100),
    "wind_speed": (0, 60),
    "pressure": (800, 1_100),
}

# India meteorological seasons.
def season_of(month: int) -> str:
    if month in (12, 1, 2):
        return "winter(DJF)"
    if month in (3, 4, 5):
        return "pre-monsoon(MAM)"
    if month in (6, 7, 8, 9):
        return "monsoon(JJAS)"
    return "post-monsoon(ON)"


def load_all():
    files = sorted(glob.glob(RAW_GLOB))
    frames = []
    for f in files:
        d = pd.read_parquet(f)
        d["__file"] = os.path.basename(f)
        frames.append(d)
    return files, pd.concat(frames, ignore_index=True)


def main() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    files, df = load_all()
    df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)
    df["hour"] = df["timestamp"].dt.floor("h")
    df["month"] = df["timestamp"].dt.month
    df["season"] = df["month"].map(season_of)

    report = []
    R = report.append

    R("# MDP Data-Quality Report (Phase A)\n")
    R(f"Source: `{RAW_GLOB}` — {len(files)} station files.\n")
    R("Generated by `audit/data_audit.py`; raw data unmodified.\n")

    # ---- 1. Scale & temporal coverage --------------------------------------
    tmin, tmax = df["timestamp"].min(), df["timestamp"].max()
    span_h = int((tmax - tmin).total_seconds() // 3600) + 1
    distinct_h = df["hour"].nunique()
    R("## 1. Scale & temporal coverage\n")
    R(f"- Stations: **{len(files)}**")
    R(f"- Total rows (station-hours present): **{len(df):,}**")
    R(f"- Timestamp dtype: `{df['timestamp'].dtype}` (UTC)")
    R(f"- Span: **{tmin}** → **{tmax}**  ({span_h} hourly slots)")
    R(f"- Distinct hours observed anywhere: **{distinct_h}**")
    R(f"- Full 204×8760 grid would be **{len(files)*8760:,}** station-hours; "
      f"present rows are **{len(df)/(len(files)*8760):.2%}** of it.\n")
    R("> Boundary note: the span starts 2024-12-31 18:00Z and ends 2025-12-30 "
      "17:00Z — offset from a clean calendar-2025 UTC window, consistent with an "
      "IST (UTC+5:30) vs UTC edge effect from the collection window. Impact is "
      "≤1 day at each edge; disclosed, not corrected.\n")

    # ---- 2. Duplicates ------------------------------------------------------
    dup = df.duplicated(subset=["station_id", "hour"]).sum()
    R("## 2. Duplicates\n")
    R(f"- Duplicate (station_id, hour) rows: **{dup}**\n")

    # ---- 3. Per-station operating periods & completeness -------------------
    rows = []
    for sid, g in df.groupby("station_id"):
        t0, t1 = g["hour"].min(), g["hour"].max()
        active = int((t1 - t0).total_seconds() // 3600) + 1
        present = g["hour"].nunique()
        rows.append({
            "station_id": sid,
            "city": g["city"].iloc[0],
            "first": t0, "last": t1,
            "active_span_h": active,
            "present_h": present,
            "within_active_coverage": present / active if active else np.nan,
            "within_year_coverage": present / 8760,
            "n_pollutants": sum(c in g.columns and g[c].notna().any() for c in POLLUTANTS),
        })
    st = pd.DataFrame(rows).sort_values("within_year_coverage", ascending=False)
    st.to_csv(f"{OUT_DIR}/station_operating_periods.csv", index=False)
    R("## 3. Station operating periods & completeness\n")
    R(f"- Median within-year coverage: **{st['within_year_coverage'].median():.1%}** "
      f"(min {st['within_year_coverage'].min():.1%}, max {st['within_year_coverage'].max():.1%})")
    R(f"- Median within-active-span coverage: **{st['within_active_coverage'].median():.1%}** "
      "(gaps remain even while a station is nominally operating)")
    R(f"- Stations with <50% within-year coverage: **{(st['within_year_coverage']<0.5).sum()}**")
    R("- Full table: `audit/reports/station_operating_periods.csv`\n")

    # ---- 4. Pollutant availability (structural vs missing) -----------------
    R("## 4. Pollutant availability\n")
    avail = []
    grid_present = len(df)
    for c in POLLUTANTS + WEATHER:
        files_with = sum(1 for f in files if c in pd.read_parquet(f, columns=None).columns)
        n_nonnull = int(df[c].notna().sum()) if c in df.columns else 0
        avail.append({
            "variable": c,
            "stations_with_column": files_with,
            "stations_without_column": len(files) - files_with,
            "nonnull_rows": n_nonnull,
            "nonnull_frac_of_present_rows": n_nonnull / grid_present,
        })
    av = pd.DataFrame(avail)
    av.to_csv(f"{OUT_DIR}/pollutant_availability.csv", index=False)
    R(av.to_markdown(index=False))
    R("")
    R("> **Completeness is conditional on existing rows.** A variable's "
      "`nonnull_frac_of_present_rows` is high only among station-hours that "
      "exist at all; absolute coverage over the full year is far lower (Section 3). "
      "Three kinds of absence must not be conflated:")
    R(">  - **Structural**: the station has no such sensor (no column).")
    R(">  - **Intermittent**: sensor exists but the hour is missing/NaN.")
    R(">  - **Below detection**: not distinguishable here — no detection-limit or")
    R(">    quality flags are present (Section 6).\n")
    R("> **VOC is structurally absent from all 204 stations.** Any VOC variable "
      "downstream is a modelling artefact, not a measurement.\n")

    # ---- 5. Seasonal availability ------------------------------------------
    seas = (df.assign(**{c: df[c].notna() for c in POLLUTANTS})
            .groupby("season")[POLLUTANTS].sum())
    seas_rows = df.groupby("season").size().rename("rows")
    seas = seas.join(seas_rows)
    seas.to_csv(f"{OUT_DIR}/seasonal_availability.csv")
    R("## 5. Seasonal availability (non-null counts)\n")
    R(seas.to_markdown())
    R("\n> Monsoon (JJAS) wash-out and seasonal sensor downtime bias which hours "
      "are observed; pooled statistics are not season-balanced.\n")

    # ---- 6. Units / provenance / flags -------------------------------------
    extra = [c for c in df.columns if c not in ID_COLS + POLLUTANTS + WEATHER
             + ["__file", "hour", "month", "season"]]
    R("## 6. Units, provenance, detection limits, quality flags\n")
    R(f"- Non-standard columns carrying metadata: **{extra or 'none'}**")
    R("- **Measurement units are NOT stored.** OpenAQ v3 returns a unit per "
      "sensor, but the collector discarded it, so units are **unverified**. "
      "Per-station magnitudes (Phase A2) indicate CO is uniformly on an mg/m³ "
      "scale while the other pollutants are µg/m³ (~×1000 apart), so absolute "
      "cross-pollutant magnitudes are not comparable. NOTE: an earlier version of "
      "this audit speculated a *cross-station* mg/m³-vs-µg/m³ mix for CO; "
      "`audit/phase_a2_units.py` shows that is NOT the case (uniform regime; the "
      "1490 max is sporadic spikes). Confirm units with `audit/fetch_units.py`.")
    R("- No detection limits, instrument/provider identifiers, or QA/QC flags "
      "are present. Below-detection values cannot be distinguished from true lows.")
    R("- **Weather provenance:** temperature/humidity/wind/pressure come from the "
      "**Open-Meteo reanalysis (modelled)**, not station instruments, and were "
      "attached by nearest ~0.1° grid cell. They are modelled covariates, not "
      "co-located observations.\n")

    # ---- 7. Suspicious values ----------------------------------------------
    R("## 7. Suspicious values (screening, not removal)\n")
    flags = []
    for c, (lo, hi) in PLAUSIBLE.items():
        if c not in df.columns:
            continue
        s = df[c]
        n = int(s.notna().sum())
        neg = int((s < 0).sum())
        zero = int((s == 0).sum())
        out = int(((s < lo) | (s > hi)).sum())
        flags.append({"variable": c, "n": n, "negatives": neg, "zeros": zero,
                      "out_of_range": out, "min": float(np.nanmin(s)) if n else np.nan,
                      "p99_9": float(np.nanpercentile(s, 99.9)) if n else np.nan,
                      "max": float(np.nanmax(s)) if n else np.nan})
    fl = pd.DataFrame(flags)
    fl.to_csv(f"{OUT_DIR}/value_screening.csv", index=False)
    R(fl.to_markdown(index=False))
    R("\n> Zeros in pollutant columns are ambiguous (true low, below-detection, or "
      "sensor fault) and must not be treated as validated measurements.\n")

    # ---- 8. Geographic coverage --------------------------------------------
    R("## 8. Geographic coverage\n")
    ncity = df["city"].nunique()
    R(f"- Distinct station labels (city field): **{ncity}**")
    R("- Stations are concentrated in the OpenAQ-reporting urban network (heavily "
      "Delhi-NCR and other metros). This is **not** a spatially representative "
      "sample of India; national-scale claims are unsupported.\n")

    # ---- machine-readable summary ------------------------------------------
    summary = {
        "n_stations": len(files),
        "n_rows": int(len(df)),
        "span_start_utc": str(tmin), "span_end_utc": str(tmax),
        "grid_completeness_vs_204x8760": len(df) / (len(files) * 8760),
        "duplicate_station_hours": int(dup),
        "voc_present": bool("voc" in df.columns),
        "units_stored": False,
        "weather_source": "open-meteo reanalysis (modelled)",
        "median_within_year_coverage": float(st["within_year_coverage"].median()),
    }
    with open(f"{OUT_DIR}/audit_summary.json", "w") as fh:
        json.dump(summary, fh, indent=2)

    with open(f"{OUT_DIR}/data_quality_report.md", "w") as fh:
        fh.write("\n".join(report))
    print("\n".join(report))
    print(f"\nWrote: {OUT_DIR}/data_quality_report.md, audit_summary.json, "
          "station_operating_periods.csv, pollutant_availability.csv, "
          "seasonal_availability.csv, value_screening.csv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
